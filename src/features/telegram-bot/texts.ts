export const texts: Record<BotLocale, Dict> = { hy, ru, en };

export function t(locale: BotLocale | null, key: TextKey, vars: Record<string, string | number> = {}): string {
  return texts[locale ?? "hy"][key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
