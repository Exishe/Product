// Generates TypeScript for the `api` schema's functions from the database
// (the Supabase type generator only covers `public`). Reads the plain-Postgres
// harness after `npm run test:sql`, or any database given in PG* env vars.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const env = {
  ...process.env,
  PGHOST: process.env.PGHOST ?? "/var/lib/postgresql/rosdata",
  PGPORT: process.env.PGPORT ?? "54329",
  PGUSER: process.env.PGUSER ?? "postgres",
  PGDATABASE: process.env.PGDATABASE ?? "ros_test",
};

const sql = `
select json_agg(json_build_object(
  'name', p.proname,
  'args', coalesce((
    select json_agg(json_build_object('name', a.name, 'type', a.type, 'optional', a.ord > p.pronargs - p.pronargdefaults) order by a.ord)
    from unnest(p.proargnames[1:p.pronargs], string_to_array(oidvectortypes(p.proargtypes), ', ')) with ordinality as a(name, type, ord)
  ), '[]'::json),
  'returns', format_type(p.prorettype, null),
  'set', p.proretset
) order by p.proname)
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'api'`;

type Fn = { name: string; args: { name: string; type: string; optional: boolean }[]; returns: string; set: boolean };
const fns: Fn[] = JSON.parse(execFileSync("psql", ["-qtA", "-c", sql], { env, encoding: "utf8" }).trim());

function ts(type: string): string {
  if (type.endsWith("[]")) return `${ts(type.slice(0, -2))}[]`;
  const t = type.replace(/^public\./, "");
  if (["uuid", "text", "character varying", "timestamp with time zone", "date", "time without time zone"].includes(t)) return "string";
  if (["integer", "smallint", "bigint", "numeric", "double precision"].includes(t)) return "number";
  if (t === "boolean") return "boolean";
  if (t === "jsonb" || t === "json") return "Json";
  if (t === "void") return "undefined";
  if (["app_locale", "member_role", "ticket_status", "service_request_kind", "payment_method", "order_source"].includes(t))
    return `Enums["${t}"]`;
  throw new Error(`No TypeScript mapping for ${type}`);
}

const body = fns
  .map((f) => {
    const args = f.args.map((a) => `        ${a.name}${a.optional ? "?" : ""}: ${ts(a.type)}`).join("\n");
    const ret = f.set ? `${ts(f.returns)}[]` : ts(f.returns);
    return `${f.name}: { Args: ${args ? `{\n${args}\n}` : "Record<string, never>"}; Returns: ${ret} };`;
  })
  .join("\n");

const out = `// Generated by scripts/gen-api-types.ts from the database. Do not edit.
import type { Database as Generated, Json } from "./types";

type Enums = Generated["public"]["Enums"];

export type ApiSchema = {
  Tables: { [_ in never]: never };
  Views: { [_ in never]: never };
  Functions: {
${body}
  };
  Enums: { [_ in never]: never };
  CompositeTypes: { [_ in never]: never };
};

export type Database = Generated & { api: ApiSchema };
`;
writeFileSync("src/lib/supabase/database.ts", out);
execFileSync("npx", ["prettier", "--write", "src/lib/supabase/database.ts"], { stdio: "ignore" });
console.log(`api types: ${fns.length} functions`);
